"""Assemble FINDINGS.md from whatever the notebooks have produced.

Safe to run at any point -- each section is skipped with a note if its inputs are not
there yet, so this can be run mid-chain and again at the end.

    python summarise_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
R = HERE / "results"
OUT = HERE / "FINDINGS.md"


def scored(df):
    """Drop the zero-bot cell before any headline mean.

    With no bots S_B is undefined and DI = 100 for every policy that lets everyone
    through, so averaging that cell in rewards permissiveness. It is what turned a proxy
    agent that challenges NOBODY into "recovers 81% of the oracle" when the honest figure
    is 65%. Report the all-six average only where continuity with the published Table 4
    requires it, and label it.
    """
    if df is None or "bots" not in getattr(df, "columns", []):
        return df
    return df[df.bots > 0]


def _read(name, **kw):
    p = R / name
    return pd.read_csv(p, **kw) if p.exists() else None


def _json(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def md(df, **kw):
    return df.to_markdown(**kw) if df is not None else "_not produced yet_"


def section(title, body):
    return f"\n## {title}\n\n{body}\n"


def main() -> str:
    parts = ["# Experimental findings",
             "\nGenerated by `summarise_results.py` from `experiments/results/`. "
             "Every number here comes from a notebook in this directory; nothing is "
             "hand-entered.\n"]

    # ---- 01 -------------------------------------------------------------- #
    part = _read("partition_summary.csv")
    inv = _read("session_inventory.csv")
    body = ""
    if inv is not None:
        body += (f"**{len(inv)} recordings** — {int((~inv.is_bot).sum())} human, "
                 f"{int(inv.is_bot.sum())} automated, {int(inv.movements.sum()):,} mouse "
                 f"movements across two collection campaigns.\n\n")
    body += ("The published LSTM split was by directory, and the two directories are "
             "separate campaigns three months apart: **zero filename overlap, zero "
             "content-hash overlap**. It is a temporal holdout, stronger than a random "
             "window split. The manuscript never says so.\n\n"
             "The leak is at the RL stage: `offline_training.z.py` sets "
             "`DATA_DIR = \"data\"`, so the agent trained on, and was evaluated on, the "
             "same recordings that are the LSTM's test set — and which selected the "
             "LSTM checkpoint via `EarlyStopping(restore_best_weights=True)`.\n\n"
             + md(part, index=False))
    parts.append(section("1. Data audit and the clean partition", body))

    # ---- 02 -------------------------------------------------------------- #
    var = _read("scorer_variants.csv")
    boot = _read("scorer_bootstrap.csv")
    choice = _json("scorer_choice.json")
    body = ""
    if var is not None:
        cols = [c for c in ["variant", "features", "win_AUC", "win_AUC_sd", "sess_AUC",
                            "sess_AUC_sd", "ECE", "ECE_sd", "ECE_after_T"] if c in var]
        body += md(var[cols].round(3), index=False) + "\n\n"
    if boot is not None:
        body += ("Paired bootstrap over sessions, against the published `xy` "
                 "representation:\n\n" + md(boot.round(3), index=False) + "\n\n")
        if not boot.distinguishable.any():
            body += ("**No representation is distinguishable from any other on this "
                     "data.** Every interval straddles zero. The timestamp question "
                     "(R1.7) cannot be answered from 52 held-out sessions — which is "
                     "itself a finding and belongs in the paper as one.\n\n")
    body += ("Independent of that: the published model is fed `[[x, y]]` only, so the "
             "manuscript's acceleration and jerk description refers to features the "
             "network never receives. That text has to change regardless of whether "
             "adding timing would help.\n\n")
    if choice:
        body += f"Scorer carried forward: `{choice['chosen']}` — rule: {choice['rule']}.\n"
    parts.append(section("2. Behavioural scorer: timestamps, perturbation, calibration", body))

    # ---- 03 -------------------------------------------------------------- #
    cmp = _read("clean_partition_DI_comparison.csv", index_col=0)
    body = md(cmp) if cmp is not None else "_not produced yet_"
    if cmp is not None and "leakage effect" in cmp.columns:
        static = [i for i in cmp.index if i.startswith("Static")]
        bias = cmp.loc[static, "leakage effect"].mean()
        body += (f"\n\nThe untrained baselines' gap between the same two pools is "
                 f"**{bias:+.1f} DI**, which is intrinsic pool difficulty rather than "
                 f"memorisation. Subtract it before calling any of the learned policies' "
                 f"`leakage effect` a leak.\n\n"
                 "`clean` vs `leaky control` holds agent, budget and scorer fixed and "
                 "varies only whether the evaluation recordings were seen in training. "
                 "`clean - paper` additionally mixes in a shorter run on a smaller pool, "
                 "so it is **not** a measure of leakage on its own.")
    parts.append(section("3. Table 4 on a clean partition", body))

    # ---- 03b ------------------------------------------------------------- #
    cross = _read("leakage_crossfit.csv")
    body = ("Notebook 03's size-matched control failed, and its own output shows why: "
            "**Static Multi-Threshold posted a seen-minus-unseen gap of +23.2 DI, and it "
            "never trains on anything.** Pool difficulty swamped the effect.\n\n"
            "03b swaps roles instead. Two agents are trained on two halves; each half "
            "serves once as seen and once as unseen, so pool difficulty enters both "
            "sides of the difference and cancels by construction. For an untrained "
            "policy the two sets are literally the same runs, so its gap must be exactly "
            "zero -- which the notebook asserts as an implementation check.\n\n")
    if cross is not None:
        import numpy as _np
        g = cross.groupby("policy").agg(seen=("seen", "mean"), unseen=("unseen", "mean"),
                                        gap=("gap", "mean"), sd=("gap", "std"),
                                        n=("gap", "size"))
        g["se"] = g.sd / _np.sqrt(g.n)
        g["ci_lo"] = (g.gap - 1.96 * g.se).round(1)
        g["ci_hi"] = (g.gap + 1.96 * g.se).round(1)
        body += md(g.drop(columns=["sd", "n"]).round(2)) + "\n\n"
        body += ("The mechanism is identified by the ablation. The no-Humanity-Score "
                 "agent sees only `[captchas_solved, last_threat, n_active]` -- nothing "
                 "that identifies a recording -- and shows **exactly zero** leakage. The "
                 "full agent, whose state includes the behavioural score, is the one "
                 "that leaks. So the overlap reached the agent through the scorer's "
                 "outputs on recordings it had trained on, and nowhere else.\n\n"
                 "**This is the number the revision should report for R1.2**, not the "
                 "drop from the published Table 4 in section 3.")
    parts.append(section("3b. How much did the train/eval overlap actually cost?", body))

    # ---- 04 -------------------------------------------------------------- #
    sens = _read("reward_sensitivity_runs.csv")
    ab = _read("abandonment_sensitivity.csv")
    body = ""
    if sens is not None:
        s = sens.groupby("reward_setting").DI.agg(["mean", "std"]).round(1).sort_values(
            "mean", ascending=False)
        body += ("Agents **retrained** under each reward setting, all evaluated with the "
                 "same metrics:\n\n" + md(s) + "\n\n")
        statics = [i for i in s.index if i.startswith("Static")]
        best_static = s.loc[statics, "mean"].max() if statics else None
        if best_static is not None:
            learned = s.drop(index=statics)
            n = int((learned["mean"] > best_static).sum())
            body += (f"**{n}/{len(learned)} reward settings still produce an agent that "
                     f"beats every static baseline** (best static {best_static:.1f} DI). "
                     "That turns \"the constants were hand-chosen\" into \"the conclusion "
                     "is robust to them\".\n\n")
    body += ("A framing point for the paper: in this simulator the reward parameters "
             "cannot change Table 4 for a *fixed* policy. Survival depends only on "
             "whether the bot was blocked and whether the user abandoned; `beta`, "
             "`R_leak` and the overkill coefficient enter the reward value and nothing "
             "else. **Reward parameters matter only through training**, which is why "
             "this notebook retrains rather than re-scores.\n\n")
    if ab is not None:
        body += ("The abandonment curve is the one parameter that moves the metrics "
                 "directly, for every policy at once:\n\n"
                 + md(ab.groupby(["curve", "policy"]).DI.mean().unstack().round(1)))
    parts.append(section("4. Reward sensitivity", body))

    # ---- 05 -------------------------------------------------------------- #
    abl = _read("population_feature_ablation.csv")
    traffic = _read("independent_traffic_runs.csv")
    body = ""
    if traffic is not None:
        cell = traffic.groupby(["policy", "n_humans", "n_bots"]).DI.mean().unstack(0)
        win = cell.idxmax(axis=1).value_counts(normalize=True).round(3)
        body += ("Humans and bots varied independently over a 5x6 grid. Share of the "
                 f"{len(cell)} cells won by each policy:\n\n" + md(win.to_frame("share")) + "\n\n")
    if abl is not None:
        a = abl.groupby("variant").DI.agg(["mean", "std"]).round(1)
        body += md(a) + "\n\n"
        body += ("Only the **frozen** variant is a valid test: it keeps the input inside "
                 "the training distribution and removes just its information. The "
                 "randomised variant also pushes the input out of distribution, so its "
                 "collapse is ordinary OOD failure, not evidence of reliance. Freezing "
                 "the population feature at a constant costs nothing, so the policy is "
                 "**not** reading the attack level off total population.\n")
    parts.append(section("5. Independent traffic and the DoS confound", body))

    # ---- 06 -------------------------------------------------------------- #
    ladder = _read("action_model_ladder.csv")
    alpha = _read("alpha_sweep.csv")
    sto = _read("stochastic_runs.csv")
    body = ("The published rule `T > B_s` is the `alpha -> infinity` limit of a "
            "two-parameter logistic item-response model, so the probabilistic "
            "environment is a continuous deformation of the published one rather than a "
            "different environment. Verified to the survivor: **144/144 exact matches** "
            "against `rlcaptcha.simulate.run_simulation`.\n\n")
    if ladder is not None:
        body += "The level ladder, with its sources:\n\n" + md(ladder.round(3), index=False) + "\n\n"
    if alpha is not None:
        body += ("Published policies as the world becomes stochastic (average DI):\n\n"
                 + md(alpha.groupby(["alpha", "policy"]).DI.mean().unstack().round(1)) + "\n\n")
    if sto is not None:
        g = scored(sto[sto.environment == "grounded"]).groupby("policy")[
            ["DI", "false_positive_rate", "mean_friction_s"]].mean().round(3)
        body += ("Retrained inside the probabilistic environment:\n\n" + md(g) + "\n\n"
                 "False-positive rate is a quantity the deterministic simulator could "
                 "not express at all — in it, a legitimate user never fails a challenge.")
    parts.append(section("6. A probabilistic action model", body))

    # ---- 07 -------------------------------------------------------------- #
    amb = _read("observability.csv")
    comp07 = _read("proxy_vs_oracle_runs.csv")
    lab = _read("label_probability_sweep.csv")
    body = ("A deployed controller knows neither the user's class nor `B_s` at decision "
            "time, and the immediate signal is ambiguous: *challenge failed, session "
            "ends* is a blocked bot **or** a false-positived human; *challenge passed, "
            "session continues* is a leaked bot **or** a satisfied human. The proxy "
            "reward is a pure function of the observable tuple, so both members of each "
            "pair get identical immediate reward. Class information reaches the agent "
            "only through a delayed, sparse, noisy abuse label.\n\n")
    if amb is not None:
        body += md(amb.round(3), index=False) + "\n\n"
    if comp07 is not None:
        # Zero-bot cells are EXCLUDED. With no bots, S_B is undefined and DI = 100 for
        # any policy that lets everyone through, so including them rewards permissiveness
        # -- it is what made a proxy agent that challenges nobody look like it recovered
        # 81% of the oracle when the honest figure is 65%. nb_07's own log said
        # "inflated, do not quote"; this function quoted it anyway.
        g = scored(comp07).groupby("policy")[["DI", "BOS", "SI_F1", "false_positive_rate"]]\
                  .mean().round(3)
        body += md(g) + "\n\n*Zero-bot cells excluded throughout (see §7 of the "\
                        "round-2 handoff).*\n\n"
        try:
            o = g.loc["DQN (oracle reward)", "DI"]
            p = g.loc["DQN (proxy reward)", "DI"]
            body += (f"**The proxy-trained agent recovers {p / o:.0%} of the "
                     f"oracle-trained agent's average DI** ({p:.1f} vs {o:.1f}), judged "
                     "entirely on ground-truth labels it never saw during training.\n\n")
        except KeyError:
            pass
    if lab is not None:
        lb = scored(lab)
        body += ("**Label coverage is not the binding constraint.** Raising the share of "
                 "abusive sessions that get confirmed from 2% to 100% barely moves the "
                 "agent:\n\n"
                 + md(lb.groupby("label_probability")[["DI", "humans_left", "bots_left"]]
                      .mean().round(2)) + "\n\n")

    pen = _read("abuse_penalty_sweep.csv")
    cred = _read("credit_window_probe.csv")
    if pen is not None:
        body += ("**Neither is the penalty weight.** Holding coverage at 0.3 and sweeping "
                 "the abuse penalty (the arithmetic break-even is around 260):\n\n"
                 + md(scored(pen).groupby("abuse_penalty")[
                     ["DI", "humans_left", "bots_left", "friction_s"]].mean().round(2))
                 + "\n\nOnly at -2400 does the agent defend at all, and it still leaks "
                   "~9x what the oracle-trained agent does. At -9600 it reverts to doing "
                   "nothing, which is consistent with training instability at large "
                   "reward magnitudes rather than with any property of the reward.\n\n")
    if cred is not None:
        body += ("**Nor is credit assignment.** Spreading the penalty across the whole "
                 "session instead of its last three steps makes matters worse, by "
                 "diluting the per-step signal:\n\n"
                 + md(cred.round(2), index=False) + "\n\n")

    body += ("### The honest conclusion\n\n"
             "A reward built only from observable signals produces a **usable** policy "
             "but not a **secure** one, and no configuration tested here closes the gap: "
             "label coverage 0.02-1.0, abuse penalty -150 to -9600, credit window 3 or "
             "12 steps. The asymmetry is structural -- friction and abandonment are "
             "observed immediately and exactly on every session, abuse only rarely, late "
             "and noisily -- so an agent optimising the observable signal systematically "
             "under-weights security.\n\n"
             "This is a limitation to publish with the evidence attached, not a solved "
             "substitution. It says Reviewer 1's deployment-reward objection is deeper "
             "than a reward-engineering exercise, which is worth more to the field than "
             "the positive result we set out to find.")
    parts.append(section("7. A reward the system could actually have", body))

    # ---- 08 -------------------------------------------------------------- #
    var8 = _read("variance_decomposition.csv")
    boot8 = _read("session_bootstrap.csv")
    curve = _read("learning_curve.csv")
    div = _read("perturbation_diversity.csv")
    body = ""
    if var8 is not None:
        body += ("Where the uncertainty actually lives:\n\n"
                 + md(var8.round(3), index=False) + "\n\n")
        share = var8.share_session_level.mean()
        body += (f"**{share:.0%} of the variance is between recording pools, not between "
                 "simulation seeds.** The +/- currently reported in the paper measures "
                 "simulation wobble with the recordings held fixed, which will be tight "
                 "no matter how small the pool is. It is not the uncertainty a reader "
                 "cares about.\n\n")
    if boot8 is not None:
        body += ("Session-level bootstrap confidence intervals:\n\n"
                 + md(boot8.round(1), index=False) + "\n\n")
    if curve is not None:
        g = curve.groupby("fraction").DI.agg(["mean", "std"]).round(2)
        body += "Learning curve over pool size:\n\n" + md(g) + "\n\n"
    if div is not None:
        body += ("How different two simulated users drawn from one recording really are:"
                 "\n\n" + md(div.round(5), index=False) + "\n\n"
                 "Under the published rigid perturbation the score moves by ~1e-3, so "
                 "two \"different\" users are the same sample. The effective sample size "
                 "of an episode is the number of **recordings** drawn, not the number of "
                 "simulated users.")
    parts.append(section("8. Is the dataset big enough?", body))

    # ---- 09 / 10 / 10b / 11 : the scorer -------------------------------- #
    eff = _read("effective_sample_size.csv")
    cvs = _read("cv_scheme_comparison.csv")
    body = ("The 44 human recordings come from **3 participants**, across two collection "
            "sittings three months apart. Participant and setup are therefore "
            "confounded: the features that most separate the two campaigns are "
            "`pause_frac` and `dt_median`, which change with hardware and browser as "
            "readily as with the person.\n\n")
    if eff is not None:
        body += md(eff, index=False) + "\n\n"
    if cvs is not None:
        body += ("Same model, two validation schemes:\n\n" + md(cvs.round(3), index=False)
                 + "\n\nSession-level splitting is optimistic because held-out "
                   "recordings come from the same three people. Leave-one-campaign-out "
                   "is the closest available proxy for an unseen participant and setup, "
                   "and both belong in the paper.\n\n")
    body += ("**Not supportable at n=3:** 'generalises to human users'. "
             "**Supportable:** 'distinguishes these three participants from these four "
             "bot generators', with both numbers reported.")
    parts.append(section("9. Three participants: what the data can support", body))

    rb = _read("robustness_seeds.csv")
    tim = _read("timing_vs_position.csv", index_col=0)
    arch = _json("scorer_arch_choice.json")
    body = ("The published scorer has 304,049 parameters fitted on ~206 windows -- about "
            "1,170 per training sample. Searching architecture, representation, learning "
            "rate and dropout by 5-fold cross-validation grouped by recording, over all "
            "156 sessions:\n\n")
    if rb is not None:
        t = rb.pivot_table(index=["spec", "representation", "params"], columns="scheme",
                           values="session_auc", aggfunc=["mean", "std"]).round(3)
        t.columns = [f"{a}_{b}" for a, b in t.columns]
        t = t.reset_index().sort_values("mean_CV", ascending=False)
        t["optimism"] = (t.mean_CV - t.mean_LOCO).round(3)
        body += md(t, index=False) + "\n\n"
    if arch:
        body += (f"**Selected: `{arch['spec']}` on `{arch['representation']}`, "
                 f"{arch['params']:,} parameters** -- 55x smaller than the published "
                 f"model and better on every axis: cross-validated session AUC "
                 f"{arch['cv_session_auc']:.3f}, unseen-campaign {arch['loco_session_auc']:.3f}, "
                 f"ECE {arch['ece_cv']:.3f}.\n\n")
    if tim is not None:
        body += ("### Do timestamps help? No -- dropping absolute position does\n\n"
                 "`dxdy_dt` changes two things against `xy` at once. `dxdy` "
                 "(differences, no timing) isolates the first:\n\n"
                 + md(tim.round(3)) + "\n\n")
        for c in tim.columns:
            v = tim[c]
            body += f"* `{c}` — mean {v.mean():+.3f}, positive in {int((v>0).sum())}/6\n"
        body += ("\nAdding timing barely moves cross-validated performance and its sign "
                 "flips between architectures. Worse, it **more than doubles the "
                 "optimism gap** (0.087 -> 0.222): inter-event timing largely encodes "
                 "the client's sampling rate, which is exactly what separates the two "
                 "campaigns. The manuscript's acceleration/jerk language should be "
                 "replaced with *the model reads relative motion, not absolute position "
                 "or timing*.\n")
    parts.append(section("10. The right-sized scorer", body))

    aug = _read("augmentation_sweep.csv")
    fin = _read("final_scorer_calibration.csv")
    fam = _read("final_scorer_per_family.csv")
    sens = _read("perturbation_sensitivity_final.csv")
    body = ""
    if aug is not None:
        a = aug.groupby("augmentation").agg(
            sess_auc=("session_auc", "mean"), sd=("session_auc", "std"),
            ece_T=("ece_after_T", "mean")).sort_values("sess_auc", ascending=False)
        body += ("Augmentation, 3 seeds each, on the selected model:\n\n"
                 + md(a.round(4)) + "\n\n"
                 "**No augmentation wins.** This reverses what notebook 02 suggested, "
                 "and the reason is instructive: per-movement jitter helped when the "
                 "model was a 304k-parameter network reading *absolute* coordinates, "
                 "because it damped a badly overparameterised fit. On a right-sized "
                 "model reading *differences*, the same jitter corrupts the signal "
                 "directly -- a 1px perturbation of each point is a large relative "
                 "change to a step of a few pixels. Augmentation was compensating for a "
                 "mis-specified model; fix the model and it is no longer needed.\n\n")
    if sens is not None:
        body += ("Score sensitivity to each perturbation (sd across 8 copies of one "
                 "chunk) confirms the published rigid shift creates nothing:\n\n"
                 + md(sens.round(5), index=False) + "\n\n")
    if fin is not None:
        body += ("Final scorer on the unseen `eval` pool, trained on the `lstm` pool "
                 "only so the RL pools stay clean:\n\n" + md(fin.round(4), index=False)
                 + "\n\n")
    if fam is not None:
        body += ("Per bot family:\n\n" + md(fam.round(3), index=False) + "\n\n"
                 "FallibleBot is the hardest family and HumanishBot the easiest, which "
                 "is worth reporting -- a single aggregate hides that the families are "
                 "not equally difficult.\n")
    parts.append(section("11. Augmentation and the final calibrated scorer", body))

    text = "\n".join(parts)
    OUT.write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    main()
    print(f"wrote {OUT}")
